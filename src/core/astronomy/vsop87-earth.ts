function sumSeries(terms: ReadonlyArray<Term>, tau: number): number {
    let total = 0;
    for (const [amplitude, phase, rate] of terms) {
        total += amplitude * Math.cos(phase + rate * tau);
    }
    return total;
}

/**
 * 지구의 헬리오센트릭 황경 (라디안).
 * @param jde 지구시(TT) 기준 율리우스 적일
 */
export function earthHeliocentricLongitude(jde: number): number {
    const tau = (jde - 2451545.0) / 365250;
    return (
        sumSeries(EARTH_L0, tau)
        + sumSeries(EARTH_L1, tau) * tau
        + sumSeries(EARTH_L2, tau) * tau * tau
    ) / 1e8;
}

/**
 * 지구-태양 거리 (AU). 광행차가 거리에 반비례해서 필요하다.
 * @param jde 지구시(TT) 기준 율리우스 적일
 */
export function earthRadiusVector(jde: number): number {
    const tau = (jde - 2451545.0) / 365250;
    return (sumSeries(EARTH_R0, tau) + sumSeries(EARTH_R1, tau) * tau) / 1e8;
}
